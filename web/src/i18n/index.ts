const stored = (() => {
  try {
    return localStorage.getItem(STORAGE_KEY)
  } catch {
    return null
  }
})()

function detectLocale(): AppLocale {
  if (stored && Object.prototype.hasOwnProperty.call(messages, stored)) return stored as AppLocale
  const language = (navigator.language || 'zh-CN').toLowerCase()
  if (language.startsWith('ja')) return 'ja-JP'
  if (language.startsWith('en')) return 'en-US'
  return 'zh-CN'
}

export const locale = ref<AppLocale>(detectLocale())

export function t(key: string, params?: Record<string, string | number>): string {
  const table = messages[locale.value] ?? messages['zh-CN']
  let text = table[key] ?? messages['zh-CN'][key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value))
    }
  }
  return text
}

export function setLocale(value: AppLocale): void {
  locale.value = value
  document.documentElement.lang = value
  try {
    localStorage.setItem(STORAGE_KEY, value)
  } catch {
    // 忽略存储失败。
  }
}

export function applyLocale(): void {
  document.documentElement.lang = locale.value
}

